import {test,expect} from '@playwright/test';
test('loan detail, real simulator payment completion and unmatched visibility',async({page})=>{
  const kubernetes=process.env.SMOKE_MODE==='Kubernetes';
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('combobox').focus();await page.getByRole('combobox').press('ArrowDown');await page.getByRole('option',{name:'Admin',exact:true}).click();
  await page.getByLabel('Password',{exact:true}).fill(process.env.ADMIN_PASSWORD??'demo-admin-password');
  await page.getByRole('button',{name:'Open dashboard'}).click();
  await expect(page.getByRole('heading',{name:'Month-end, under control.'})).toBeVisible();
  await expect(page.getByText(kubernetes?'Kubernetes API.':'Unavailable in Compose.',{exact:false})).toBeVisible();
  await page.screenshot({path:kubernetes?'../artifacts/overview-kubernetes.png':'../artifacts/overview.png',fullPage:true});
  await page.getByRole('link',{name:'Explore the example loan'}).click();
  await expect(page.getByRole('heading',{name:'LOAN-1001'})).toBeVisible();
  await expect(page.getByText('Contractual installment schedule')).toBeVisible();
  await expect(page.getByText('2027-02-28',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Bank simulator',exact:true}).click();
  await page.getByRole('button',{name:'Normal 5 RPS'}).click();
  await page.getByRole('spinbutton',{name:'Target requests / second'}).fill('1');
  await page.getByRole('spinbutton',{name:'Duration (seconds)'}).fill('1');
  await page.getByRole('textbox',{name:'Fixed loan (optional)'}).fill('LOAN-1002');
  const started=page.waitForResponse(r=>r.url().endsWith('/api/v1/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Start simulation'}).click();
  const startedResponse=await started;expect(startedResponse.ok()).toBe(true);
  const runId=(await startedResponse.json()).id as string;
  await expect.poll(async()=>{const r=await page.request.get('/api/v1/runs/'+runId);return (await r.json()).run.status}).toBe('Completed');
  const transactionId='tx-'+runId.replaceAll('-','')+'-000000';
  await expect.poll(async()=>{const r=await page.request.get('/api/v1/payments/'+transactionId);if(!r.ok())return false;const b=await r.json();return ['Applied','AppliedWithCredit'].includes(b.payment.status)}).toBe(true);
  await expect(page.getByText('Applied unique transactions',{exact:true})).toBeVisible();
  await expect.poll(async()=>{const r=await page.request.get('/api/v1/run-application/'+runId);return (await r.json()).appliedUnique}).toBe(1);
  await page.getByRole('spinbutton',{name:'Unknown references (%)'}).fill('100');
  const unknownStarted=page.waitForResponse(r=>r.url().endsWith('/api/v1/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Start simulation'}).click();
  const unknownResponse=await unknownStarted;expect(unknownResponse.ok()).toBe(true);const unknownRunId=(await unknownResponse.json()).id as string;
  const unknownTransactionId='tx-'+unknownRunId.replaceAll('-','')+'-000000';
  await expect.poll(async()=>{const r=await page.request.get('/api/v1/failures');const b=await r.json();return b.loan.reviews.some((p:{bankTransactionId:string;originalReference:string})=>p.bankTransactionId===unknownTransactionId&&p.originalReference==='UNKNOWN-REFERENCE')}).toBe(true);
  await page.getByRole('link',{name:'Failures & recovery',exact:true}).click();
  await page.getByRole('textbox',{name:'Filter loaded failures by identity, reference or reason'}).fill(unknownTransactionId);
  await expect(page.getByText('UNKNOWN-REFERENCE',{exact:true}).first()).toBeVisible();
  await page.screenshot({path:kubernetes?'../artifacts/failures-kubernetes.png':'../artifacts/failures.png',fullPage:true});
  await page.getByRole('link',{name:'Payments & webhooks',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Observed transactions'})).toBeVisible();
  await expect(page.getByText('SUCCEEDED',{exact:true}).first()).toBeVisible();
  await page.getByText('SUCCEEDED',{exact:true}).first().click();
  await expect(page.getByRole('heading',{name:'Durable receipt'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Consumer & allocation'})).toBeVisible();
  await page.getByRole('button',{name:'Close this dialog'}).click();
  await page.getByRole('link',{name:'Scaling & observability',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Scaling & observability'})).toBeVisible();
  await expect(page.getByText(kubernetes?'Kubernetes API':'Unavailable in Compose',{exact:true}).first()).toBeVisible();
  if(kubernetes){await expect(page.getByText('loan-worker',{exact:true}).first()).toBeVisible();await page.screenshot({path:'../artifacts/scaling-kubernetes.png',fullPage:true});}
  await page.goto('/reconciliation?run='+runId);
  await page.getByRole('button',{name:'Compare settlement'}).click();
  await expect(page.getByRole('heading',{name:'Settlement differences & matches'})).toBeVisible();
  await expect(page.getByText('Matched',{exact:true}).first()).toBeVisible();
  expect(errors).toEqual([]);
});
